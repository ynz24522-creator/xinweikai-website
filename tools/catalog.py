def thick(size, power, volt, values, brand="uniohm", suffix="TCE"):
    """Build thick-film chip resistor rows for one package size."""
    out = []
    for v in values:
        if brand == "uniohm":
            model = "%sWGF%s%s" % (size, R4[v], suffix)
        else:  # Yageo RC series
            model = "RC%sFR-07%sL" % (size, R4[v])
        out.append(P(model, brand, size, "%s ±1%% %s %s" % (OHM_LABEL[v], power, volt), "res-thick"))
    return out


def yageo(size, power, volt, values):
    return thick(size, power, volt, values, brand="yageo")


