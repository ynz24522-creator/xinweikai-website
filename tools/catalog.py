def build_catalog():
    """Return the assembled catalogue plus summary statistics."""
    categories = []
    total_parts = 0
    total_subs = 0
    for cat in CATEGORIES:
        subs = cat["subs"]
        count = sum(len(s["parts"]) for s in subs)
        categories.append({
            "id": cat["id"],
            "zh": cat["zh"],
            "en": cat["en"],
            "blurbZh": cat["blurbZh"],
            "blurbEn": cat["blurbEn"],
            "tipsZh": cat["tipsZh"],
            "tipsEn": cat["tipsEn"],
            "count": count,
            "subs": subs,
        })
        total_parts += count
        total_subs += len(subs)
    return categories, total_parts, total_subs


